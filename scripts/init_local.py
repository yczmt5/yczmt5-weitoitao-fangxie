def main():
    if not os.path.isdir(LOCAL_DIR):
        os.makedirs(LOCAL_DIR, exist_ok=True)
        made = []
        for name, content in TEMPLATES.items():
            with open(os.path.join(LOCAL_DIR, name), "w", encoding="utf-8", newline="\n") as f:
                f.write(content)
            made.append(name)
        print("_local/ 已建好（%d 个文件）：%s" % (len(made), LOCAL_DIR))
        return 0

    missing = [n for n in TEMPLATES if not os.path.isfile(os.path.join(LOCAL_DIR, n))]
    if not missing:
        print("_local/ 已存在且齐全，跳过（不动你的记录）。")
        return 0
    for name in missing:
        with open(os.path.join(LOCAL_DIR, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(TEMPLATES[name])
    print("_local/ 已存在，补了 %d 个缺的文件：%s" % (len(missing), "、".join(missing)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
